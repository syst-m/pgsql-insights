func TestValidateCatches(t *testing.T) {
	// Validate's own logic, exercised on mutations of the real table rather than
	// on a toy table: copying the shipped table and breaking one thing means the
	// only error it can report is the one under test.
	cases := []struct {
		name   string
		mutate func(map[View]map[int]string)
		want   string
	}{
		{
			name: "empty column set",
			mutate: func(m map[View]map[int]string) {
				m[ViewStatArchiver] = map[int]string{13: "", 14: m[ViewStatArchiver][14],
					15: m[ViewStatArchiver][15], 16: m[ViewStatArchiver][16],
					17: m[ViewStatArchiver][17], 18: m[ViewStatArchiver][18]}
			},
			want: "empty column set",
		},
		{
			name: "invalid column name",
			mutate: func(m map[View]map[int]string) {
				m[ViewStatArchiver][16] = m[ViewStatArchiver][16] + " NotAColumn"
			},
			want: "not a valid column name",
		},
		{
			name: "duplicate column",
			mutate: func(m map[View]map[int]string) {
				m[ViewStatArchiver][16] = m[ViewStatArchiver][16] + " archived_count"
			},
			want: "listed twice",
		},
		{
			name: "major outside 13–18",
			mutate: func(m map[View]map[int]string) {
				m[ViewStatArchiver][19] = m[ViewStatArchiver][18]
			},
			want: "not a major the matrix covers",
		},
		{
			name: "column set shared between two views",
			mutate: func(m map[View]map[int]string) {
				m[ViewStatArchiver][18] = m[ViewLocks][18]
			},
			want: "column set also used by",
		},
		{
			name: "schema-qualified view name",
			mutate: func(m map[View]map[int]string) {
				m["pg_catalog.pg_locks"] = m[ViewLocks]
				delete(m, ViewLocks)
			},
			want: "schema-qualified",
		},
		{
			name: "a major with no views at all",
			mutate: func(m map[View]map[int]string) {
				for v, per := range m {
					delete(per, 18)
					m[v] = per
				}
			},
			want: "major 18 has no views",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			m := copyTable(columnsByMajor)
			tc.mutate(m)
			err := validate(m)
			if err == nil {
				t.Fatalf("validate() returned nil, want an error containing %q", tc.want)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("validate() = %q, want it to mention %q", err, tc.want)
			}
		})
	}
}

func TestStatusOf(t *testing.T) {
	// R13.9's PostgreSQL axis, verbatim: 15 untested, 16 tested (16.11),
	// 17 tested (17.11), 18 untested, and 13/14 impossible on CNPG 1.30.
	cases := []struct {
		major int
		want  Status
	}{
		{Major13, StatusImpossible},
		{Major14, StatusImpossible},
		{Major15, StatusUntested},
		{Major16, StatusTested},
		{Major17, StatusTested},
		{Major18, StatusUntested},
	}
	for _, tc := range cases {
		got, note, ok := StatusOf(tc.major)
		if !ok {
			t.Errorf("StatusOf(%d): no cell", tc.major)
			continue
		}
		if got != tc.want {
			t.Errorf("StatusOf(%d) = %s, want %s", tc.major, got, tc.want)
		}
		// R13.9's stated point is "no silent claims", so a cell without a note is
		// the silent case: the 13/14 cells in particular have to carry the
		// fixture-tested-only half.
		if strings.TrimSpace(note) == "" {
			t.Errorf("StatusOf(%d): empty note", tc.major)
		}
	}
	if _, _, ok := StatusOf(12); ok {
		t.Error("StatusOf(12) returned a cell; the matrix starts at 13")
	}
	if _, _, ok := StatusOf(19); ok {
		t.Error("StatusOf(19) returned a cell; the matrix ends at 18")
	}
}

// --- helpers -----------------------------------------------------------------

func mustCols(t *testing.T, view View, major int) []string {
	t.Helper()
	cols, ok := Columns(view, major)
	if !ok {
		t.Fatalf("Columns(%s, %d): view not in the matrix", view, major)
	}
	return cols
}

func hasCol(cols []string, name string) bool {
	for _, c := range cols {
		if c == name {
			return true
		}
	}
	return false
}

func containsInt(haystack []int, needle int) bool {
	for _, v := range haystack {
		if v == needle {
			return true
		}
	}
	return false
}

func equalSets(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	as := append([]string(nil), a...)
	bs := append([]string(nil), b...)
	for i := range as {
		for j := i + 1; j < len(as); j++ {
			if as[i] > as[j] {
				as[i], as[j] = as[j], as[i]
			}
		}
	}
	for i := range bs {
		for j := i + 1; j < len(bs); j++ {
			if bs[i] > bs[j] {
				bs[i], bs[j] = bs[j], bs[i]
			}
		}
	}
	return reflect.DeepEqual(as, bs)
}

func copyTable(t map[View]map[int]string) map[View]map[int]string {
	out := make(map[View]map[int]string, len(t))
	for v, per := range t {
		inner := make(map[int]string, len(per))
		for m, s := range per {
			inner[m] = s
		}
		out[v] = inner
	}
	return out
}
