func TestDeclaredViewsMatchTable(t *testing.T) {
	seen := map[View]bool{}
	for _, v := range declaredViews {
		if seen[v] {
			t.Errorf("View %s listed twice in declaredViews", v)
		}
		seen[v] = true
		if _, ok := columnsByMajor[v]; !ok {
			t.Errorf("View %s is declared but has no row in columnsByMajor", v)
		}
	}
	for v := range columnsByMajor {
		if !seen[v] {
			t.Errorf("columnsByMajor has a row for %s with no declared View constant", v)
		}
	}
}

// TestSixMajorCoverage pins one number pair per major: how many views exist and
// how many columns they have in total, for each of the six majors R16.1 names.
func TestSixMajorCoverage(t *testing.T) {
	cases := []struct {
		major, views, columns int
	}{
		{Major13, 24, 300},
		{Major14, 27, 331},
		{Major15, 29, 358},
		{Major16, 30, 385},
		{Major17, 31, 399},
		{Major18, 31, 416},
	}
	for _, tc := range cases {
		if got := Majors(); !containsInt(got, tc.major) {
			t.Fatalf("Majors() does not include %d", tc.major)
		}
		views := Views(tc.major)
		if len(views) != tc.views {
			t.Errorf("major %d: %d views, want %d", tc.major, len(views), tc.views)
		}
		total := 0
		for _, v := range views {
			cols, ok := Columns(v, tc.major)
			if !ok {
				t.Errorf("major %d: Views() listed %s but Columns says it does not exist", tc.major, v)
				continue
			}
			if len(cols) == 0 {
				t.Errorf("major %d: %s has an empty column list", tc.major, v)
			}
			total += len(cols)
		}
		if total != tc.columns {
			t.Errorf("major %d: %d columns across all views, want %d", tc.major, total, tc.columns)
		}
	}
}

func TestMajors(t *testing.T) {
	want := []int{13, 14, 15, 16, 17, 18}
	if got := Majors(); !reflect.DeepEqual(got, want) {
		t.Errorf("Majors() = %v, want %v", got, want)
	}
	// R13.9's CNPG axis is 15–18, not the table's 13–18: the two lists answer
	// different questions and must not collapse into one.
	if got, want := CNPGSupported(), []int{15, 16, 17, 18}; !reflect.DeepEqual(got, want) {
		t.Errorf("CNPGSupported() = %v, want %v", got, want)
	}
	for _, m := range []int{13, 14} {
		if IsSupported(m) {
			t.Errorf("IsSupported(%d) = true, but R13.9 marks PG 13/14 impossible on CNPG 1.30", m)
		}
	}
	for _, m := range []int{15, 16, 17, 18} {
		if !IsSupported(m) {
			t.Errorf("IsSupported(%d) = false, but CNPG 1.30 supports it (R13.9)", m)
		}
	}
	for _, m := range []int{11, 12, 19, 20, 0, -1} {
		if IsSupported(m) {
			t.Errorf("IsSupported(%d) = true", m)
		}
	}
	// Mutating the returned slice must not corrupt the package's copy.
	got := Majors()
	got[0] = 99
	if Majors()[0] != 13 {
		t.Error("mutating the slice returned by Majors() changed the package's list")
	}
}

// TestR2_4EnumeratedCases asserts R2.4's own list, one requirement clause at a
// time. If the table had been written from memory, this is the test that would
// have caught it: each case below is a claim in the spec's text, restated as an
// assertion about the data.
func TestR2_4EnumeratedCases(t *testing.T) {
	t.Run("total_time becomes total_exec_time at PG13", func(t *testing.T) {
		// R2.4: "`total_time`→`total_exec_time` at PG13 (13–14 rows present but
		// unvalidated, R13.9)". The table starts at 13, so the 13 side is the
		// checkable half; succession.go carries the PG12 spelling.
		cols := mustCols(t, ViewStatStatements, Major13)
		if !hasCol(cols, "total_exec_time") {
			t.Error("pg_stat_statements at 13 lacks total_exec_time")
		}
		if hasCol(cols, "total_time") {
			t.Error("pg_stat_statements at 13 still lists total_time (that is the PG12 spelling)")
		}
		s, ok := SuccessorOf(ViewStatStatements, "total_time")
		if !ok || s.Since != Major13 {
			t.Errorf("no succession recording total_time→total_exec_time since 13: %+v", s)
		}
	})

	t.Run("blk_read_time/blk_write_time become shared_* at PG17", func(t *testing.T) {
		for _, major := range []int{Major13, Major14, Major15, Major16} {
			cols := mustCols(t, ViewStatStatements, major)
			if !hasCol(cols, "blk_read_time") || !hasCol(cols, "blk_write_time") {
				t.Errorf("pg_stat_statements at %d: missing blk_read_time/blk_write_time", major)
			}
			if hasCol(cols, "shared_blk_read_time") {
				t.Errorf("pg_stat_statements at %d: shared_blk_read_time appears before PG17", major)
			}
		}
		for _, major := range []int{Major17, Major18} {
			cols := mustCols(t, ViewStatStatements, major)
			if !hasCol(cols, "shared_blk_read_time") || !hasCol(cols, "shared_blk_write_time") {
				t.Errorf("pg_stat_statements at %d: missing shared_blk_read_time/shared_blk_write_time", major)
			}
			if hasCol(cols, "blk_read_time") || hasCol(cols, "blk_write_time") {
				t.Errorf("pg_stat_statements at %d: the unqualified blk_*_time names survive past PG16", major)
			}
		}
		// R3.2's derivation depends on this pairing, not on a split.
		for _, col := range []string{"blk_read_time", "blk_write_time"} {
			s, ok := SuccessorOf(ViewStatStatements, col)
			if !ok || s.Since != Major17 {
				t.Errorf("no succession for %s since 17: %+v", col, s)
			}
		}
	})

	t.Run("op_bytes is gone from pg_stat_io at PG18", func(t *testing.T) {
		// R2.4: "`op_bytes` removed from `pg_stat_io` at PG18". The view itself
		// only exists from 16, so 16 and 17 are the pre-image.
		for _, major := range []int{Major16, Major17} {
			if !hasCol(mustCols(t, ViewStatIO, major), "op_bytes") {
				t.Errorf("pg_stat_io at %d lacks op_bytes", major)
			}
		}
		cols := mustCols(t, ViewStatIO, Major18)
		if hasCol(cols, "op_bytes") {
			t.Error("pg_stat_io at 18 still lists op_bytes")
		}
		for _, c := range []string{"read_bytes", "write_bytes", "extend_bytes"} {
			if !hasCol(cols, c) {
				t.Errorf("pg_stat_io at 18 lacks %s (op_bytes's three successors)", c)
			}
		}
	})

	t.Run("pg_stat_wal shrinks 9 to 5 columns at PG18", func(t *testing.T) {
		// R2.4's fourth case. The view does not exist at 13, so the 9-column
		// shape spans 14–17 and the 5-column shape is 18 alone.
		for _, major := range []int{Major14, Major15, Major16, Major17} {
			if got := len(mustCols(t, ViewStatWAL, major)); got != 9 {
				t.Errorf("pg_stat_wal at %d has %d columns, want 9", major, got)
			}
		}
		if _, ok := Columns(ViewStatWAL, Major13); ok {
			t.Error("pg_stat_wal exists at 13; it was added in PG14")
		}
		got := mustCols(t, ViewStatWAL, Major18)
		want := []string{"wal_records", "wal_fpi", "wal_bytes", "wal_buffers_full", "stats_reset"}
		if !equalSets(got, want) {
			t.Errorf("pg_stat_wal at 18 = %v, want %v", got, want)
		}
	})

	t.Run("pg_stat_bgwriter shrinks 11 to 4 at PG17 and checkpoints move", func(t *testing.T) {
		// The case R2.4 calls the one a rename table gets wrong: "pg_stat_bgwriter
		// at PG17 shrinks from 11 columns to 4 (buffers_clean, maxwritten_clean,
		// buffers_alloc, stats_reset) while checkpoint stats move to a new,
		// separate view pg_stat_checkpointer".
		for _, major := range []int{Major13, Major14, Major15, Major16} {
			if got := len(mustCols(t, ViewStatBgwriter, major)); got != 11 {
				t.Errorf("pg_stat_bgwriter at %d has %d columns, want 11", major, got)
			}
		}
		got := mustCols(t, ViewStatBgwriter, Major17)
		want := []string{"buffers_clean", "maxwritten_clean", "buffers_alloc", "stats_reset"}
		if !equalSets(got, want) {
			t.Errorf("pg_stat_bgwriter at 17 = %v, want exactly the four R2.4 names %v", got, want)
		}
		if got := len(mustCols(t, ViewStatBgwriter, Major18)); got != 4 {
			t.Errorf("pg_stat_bgwriter at 18 has %d columns, want 4", got)
		}
		// The other half of the case: the view the checkpoint stats moved to.
		for _, major := range []int{Major13, Major14, Major15, Major16} {
			if _, ok := Columns(ViewStatCheckpointer, major); ok {
				t.Errorf("pg_stat_checkpointer exists at %d; it was added in PG17", major)
			}
		}
		if got := len(mustCols(t, ViewStatCheckpointer, Major17)); got != 9 {
			t.Errorf("pg_stat_checkpointer at 17 has %d columns, want 9", got)
		}
		if got := len(mustCols(t, ViewStatCheckpointer, Major18)); got != 11 {
			t.Errorf("pg_stat_checkpointer at 18 has %d columns, want 11", got)
		}
		// And the specific moves, since a rename table that kept bgwriter's four
		// survivors and forgot the five movers is the failure R2.4 names.
		for from, to := range map[string]string{
			"checkpoints_timed":     "num_timed",
			"checkpoints_req":       "num_requested",
			"checkpoint_write_time": "write_time",
			"checkpoint_sync_time":  "sync_time",
			"buffers_checkpoint":    "buffers_written",
		} {
			s, ok := SuccessorOf(ViewStatBgwriter, from)
			if !ok {
				t.Errorf("pg_stat_bgwriter.%s has no recorded successor", from)
				continue
			}
			if len(s.To) != 1 || s.To[0] != (Source{ViewStatCheckpointer, to}) {
				t.Errorf("pg_stat_bgwriter.%s → %v, want pg_stat_checkpointer.%s", from, s.To, to)
			}
		}
	})
}

func TestQueryAndSchema(t *testing.T) {
	// R2.5: every catalog reference schema-qualified, every column named.
	q, ok := Query(ViewLocks, Major16)
	if !ok {
		t.Fatal("Query(pg_locks, 16) not found")
	}
	cols, _ := Columns(ViewLocks, Major16)
	want := "SELECT " + strings.Join(cols, ", ") + " FROM pg_catalog.pg_locks"
	if q != want {
		t.Errorf("Query(pg_locks,16) =\n%s\nwant\n%s", q, want)
	}
	if strings.Contains(q, "SELECT *") {
		t.Error("Query used SELECT *: R2.5 requires the projection to name every column")
	}

	q, ok = Query(ViewStatStatements, Major17)
	if !ok {
		t.Fatal("Query(pg_stat_statements, 17) not found")
	}
	if !strings.HasSuffix(q, " FROM pg_stat_statements.pg_stat_statements") {
		t.Errorf("Query(pg_stat_statements,17) FROM clause = %q; R2.5 spells the extension's schema pg_stat_statements",
			q[strings.Index(q, " FROM "):])
	}
	if Schema(ViewStatStatementsInfo) != "pg_stat_statements" {
		t.Errorf("Schema(pg_stat_statements_info) = %q", Schema(ViewStatStatementsInfo))
	}
	if Schema(ViewStatActivity) != "pg_catalog" {
		t.Errorf("Schema(pg_stat_activity) = %q", Schema(ViewStatActivity))
	}
	if _, ok := Query(ViewStatCheckpointer, Major16); ok {
		t.Error("Query(pg_stat_checkpointer, 16) returned a statement for a view that does not exist there")
	}
}

func TestAppliesTo(t *testing.T) {
	// The seam collector.go:166's comment names: this func is what
	// collector.Applicability holds. The compile-time assertion of the fit is the
	// `var _ Applicability = pgversion.AppliesTo(...)` line in
	// internal/collector/collector_test.go — it lives there because importing
	// collector from this package would be an import cycle.
	ok := AppliesTo(ViewStatCheckpointer)
	for _, major := range []int{13, 14, 15, 16} {
		if ok(major) {
			t.Errorf("AppliesTo(pg_stat_checkpointer)(%d) = true", major)
		}
	}
	for _, major := range []int{17, 18} {
		if !ok(major) {
			t.Errorf("AppliesTo(pg_stat_checkpointer)(%d) = false", major)
		}
	}
	// A view on every major: the answer AllMajors gives, derived from the table.
	all := AppliesTo(ViewStatActivity)
	for _, major := range Majors() {
		if !all(major) {
			t.Errorf("AppliesTo(pg_stat_activity)(%d) = false", major)
		}
	}
	// A view that is not in the matrix at all: never applicable, and not a panic.
	if AppliesTo(View("pg_nope"))(16) {
		t.Error("AppliesTo(pg_nope)(16) = true")
	}
}

