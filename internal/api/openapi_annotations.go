// Code authored once and read by the generator: the prose half of
// api/openapi.yaml.
//
// R8.1b splits the document into what a generator can derive and what it cannot.
// It can derive the routes (from the mux.HandleFunc registrations), the schemas
// (from the dto's json tags) and the planned-route list (from api/x-planned-paths.yaml).
// It cannot derive prose: the info block's argument for why the envelope is
// spelled out, what a given endpoint's 404 means versus a 400, the seven YAML
// scalars that have to be quoted for the file to parse. That prose lives here,
// one []string per section, so the generator assembles a document by
// concatenating strings rather than by re-serialising YAML -- a yaml.dump of the
// document would reflow every hand-wrapped description and turn a prose edit
// into a 2000-line diff, which is the failure mode D20 records for
// gen-pgmatrix.py's whitespace.
//
// Editing this file is how the document changes: edit the prose, run
// `go test ./internal/api -run TestGeneratedOpenAPI -update` (or `make openapi`),
// and api/openapi.yaml is rewritten from it. The generator validates every entry
// against the code it is supposed to describe -- a path with no route, a schema
// whose properties are not the struct's json tags, an x-status the route table
// contradicts -- so prose and code cannot drift quietly.
//
// The strings are the document's lines verbatim, including indentation, because
// the generator's output is byte-compared against the committed file.

